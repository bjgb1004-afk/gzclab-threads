def kst(now):
    return now.astimezone(KST)


def due_post(now, queue):
    local = kst(now)
    if (local.hour, local.minute) < POST_TIME:
        return None
    done = {q["id"] for q in queue}
    return next((p for p in POSTS if p["date"] == local.date() and f"feature-{p['key']}" not in done), None)


def run_auto(now, dry=False):
    queue = json.loads(QUEUE.read_text(encoding="utf-8"))
    p = due_post(now, queue)
    if not p:
        return 0
    if dry:
        print(p["text"])
        return 0
    try:
        pid = publish.publish(p["text"])
    except Exception as e:
        publish.telegram(f"❌ 복권명당 기능 소개 글 발행 실패 ({p['key']})\n{e}")
        raise
    queue = json.loads(QUEUE.read_text(encoding="utf-8"))
    queue.append({"id": f"feature-{p['key']}", "status": "published", "slot": "feature", "text": p["text"],
                  "post_id": pid,
                  "published_at": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")})
    QUEUE.write_text(json.dumps(queue, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    publish.telegram(f"📱 복권명당 기능 소개 글 발행됨 ({p['key']})")
    return 0


